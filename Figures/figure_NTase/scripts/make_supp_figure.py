"""Supplementary figure (Plotly): AlphaFold3 ipTM / pTM for the NTase-NTP-Mg2+ panel.

WHY MULTIPLE SEEDS
A single AF3 model per NTase x NTP-pair condition (as in Figure 4C) cannot separate small
differences between substrates from AF3-prediction noise (e.g. shared-MSA artifacts), and gives
no SD or statistics. This script therefore expects up to 5 independent AF3 seeds per condition
(see inputs/af3_server_jobs/, generated by generate_af3_jobs.py), each producing the AF3
server's default 5 diffusion samples -> up to 25 models per condition.

INPUT: af3_results/**/ntase_*/*_summary_confidences_*.json (AF3 server downloads, any depth).

Robust to PARTIAL data: results are being submitted across several AF3 server accounts/days
(see inputs/af3_server_jobs/README.md for why), so at any point some (protein, NTP-pair)
conditions may have 0-4 seeds instead of the full 5. This script finds whatever is under
af3_results/ (searched recursively, any subfolder depth/name), prints a coverage table so
it's clear what's done vs still pending, and skips groups/tests that don't have enough data
yet rather than crashing - safe to re-run after every new batch of results lands.

For each protein (Bacillus phage Bcp1 NTase YP_009031408 and its Erinnyis ello granulovirus
homolog YP_009091875) and each of the 10 unordered NTP pairs drawn from {ATP, GTP, CTP, UTP}
(all with 3 Mg2+ ions; the 6 ATP/GTP/UTP pairs from Figure 4C plus 4 pairs adding CTP, which
CD-NTases are documented to use - Govande et al 2021, Whiteley et al 2019), plots box + all
per-model points for ipTM and pTM, with the per-seed mean +/- SD overlaid (where >=1 seed is
available), and reports (using only groups/pairs with enough data so far):
  - a permutation test across the NTP-pair groups that have data (per protein), on the
    per-seed means (the seed is the independent replicate)
  - pairwise exact/Monte-Carlo permutation tests per protein (n seeds vs n seeds, both >=2),
    BH-FDR corrected, written to supplementary/AF3_confidence_scores_pairwise_stats.tsv
  - the Pearson correlation between phage and viral ipTM (and pTM), across whichever NTP
    pairs currently have data for both proteins, with a bootstrap CI

USAGE: python3 scripts/make_supp_figure.py   (needs numpy, plotly, kaleido for png/pdf/svg export)

Writes supplementary/AF3_confidence_scores.{html,png,pdf,svg},
supplementary/AF3_confidence_scores_caption.txt and
supplementary/AF3_confidence_scores_coverage.tsv (what's done vs pending)
"""
