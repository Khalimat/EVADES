def subseed(path):
    d = os.path.basename(os.path.dirname(path))
    m = NAME_RE.match(d)
    if not m:
        return None
    protein = m.group("protein")
    pair = "_".join(sorted([m.group("a"), m.group("b")], key=NTP_ORDER.index))
    return protein, pair, int(m.group("seed")), m.group(5)


