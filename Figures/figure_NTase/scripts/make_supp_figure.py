    fh.write("score\tprotein\tpair_a\tpair_b\tn_seeds_a\tn_seeds_b\t"
             "mean_a\tmean_b\tdelta_b_minus_a\tperm_p_raw\tq_BH_FDR\tsignif_q_0.05\n")
    for r in pairwise_rows:
        f3 = lambda v: f"{v:.4f}" if v is not None else "NA"
        sig = "NA" if r["fdr_q"] is None else ("yes" if r["fdr_q"] < 0.05 else "no")
        fh.write(f"{r['score']}\t{r['protein']}\t{PAIR_LABEL[r['pair_a']]}\t{PAIR_LABEL[r['pair_b']]}\t"
                 f"{r['n_a']}\t{r['n_b']}\t{f3(r['mean_a'])}\t{f3(r['mean_b'])}\t{f3(r['delta'])}\t"
                 f"{f3(r['perm_p'])}\t{f3(r['fdr_q'])}\t{sig}\n")

