def perm_p(a, b):
    a, b = np.asarray(a, float), np.asarray(b, float)
    obs = abs(a.mean() - b.mean())
    pool = np.concatenate([a, b]); na = len(a); hits = tot = 0
    for idx in itertools.combinations(range(len(pool)), na):
        mask = np.zeros(len(pool), bool); mask[list(idx)] = True
        hits += abs(pool[mask].mean() - pool[~mask].mean()) >= obs - 1e-12
        tot += 1
    return hits / tot


def perm_anova_p(groups, n_iter=20000, seed=0):
    """Exact-ish (Monte Carlo) permutation test for a one-way group effect on the means."""
    rng = np.random.default_rng(seed)
    arrs = [np.asarray(g, float) for g in groups]
    sizes = [len(g) for g in arrs]
    pooled = np.concatenate(arrs)
    grand = pooled.mean()

    def stat(vals_by_group):
        return sum(len(v) * (np.mean(v) - grand) ** 2 for v in vals_by_group)

    obs = stat(arrs)
    hits = 0
    idx = np.arange(len(pooled))
    for _ in range(n_iter):
        rng.shuffle(idx)
        shuffled = pooled[idx]
        cuts = np.cumsum(sizes)[:-1]
        parts = np.split(shuffled, cuts)
        hits += stat(parts) >= obs - 1e-12
    return hits / n_iter


def bh_fdr(pvals):
    if not pvals:
        return []
    order = np.argsort(pvals)
    ranked = np.asarray(pvals)[order]
    n = len(pvals)
    q = ranked * n / (np.arange(n) + 1)
    q = np.minimum.accumulate(q[::-1])[::-1]
    out = np.empty(n)
    out[order] = np.minimum(q, 1.0)
    return out


def stars(q):
    return "****" if q < 1e-4 else "***" if q < 1e-3 else "**" if q < 1e-2 else "*" if q < 5e-2 else "ns"


# ---------------- statistics (only over pairs/groups with enough data so far) ----------------
print("Per-condition ipTM/pTM: mean +/- SD (n = seeds, up to 5 samples/seed pooled per model list)\n")
group_kw_p = {}
pairwise_rows = []
MIN_SEEDS_FOR_PAIRWISE = 2  # need >=2 vs >=2 for a non-degenerate permutation test
for k in ("iptm", "ptm"):
    for p in PROTEINS:
        print(f"  {k.upper()} {PROTEIN_LABEL[p]}")
        pairs_with_data = [pair for pair in PAIRS if len(permodel[k][p][pair]) > 0]
        for pair in PAIRS:
            vals = permodel[k][p][pair]
            sm = perseed_mean[k][p][pair]
            if not vals:
                print(f"    {PAIR_LABEL[pair]:9s} no data yet")
                continue
            sd_str = f"{np.std(vals, ddof=1):.3f}" if len(vals) > 1 else "n/a (1 model)"
            print(f"    {PAIR_LABEL[pair]:9s} n_models={len(vals):2d}  "
                  f"mean={np.mean(vals):.3f} SD={sd_str}   "
                  f"per-seed means={[round(x,3) for x in sm]}")
        if len(pairs_with_data) >= 2:
            kw = perm_anova_p([perseed_mean[k][p][pair] for pair in pairs_with_data])
            group_kw_p[(k, p)] = kw
            print(f"    -> permutation test across the {len(pairs_with_data)}/{len(PAIRS)} NTP "
                  f"pairs with data so far: p={kw:.4f}\n")
        else:
            group_kw_p[(k, p)] = None
            print(f"    -> only {len(pairs_with_data)}/{len(PAIRS)} NTP pairs have data so far; "
                  "skipping the omnibus test until >=2 are available\n")
        # pairwise: two-sided exact permutation test on per-seed means; BH-FDR corrected
        # within the family of 45 NTP-pair comparisons for this (score, protein).
        raw = []
        for a, b in itertools.combinations(PAIRS, 2):
            sa, sb = perseed_mean[k][p][a], perseed_mean[k][p][b]
            na, nb = len(sa), len(sb)
            r = dict(score=k, protein=p, pair_a=a, pair_b=b, n_a=na, n_b=nb,
                     mean_a=float(np.mean(sa)) if sa else None,
                     mean_b=float(np.mean(sb)) if sb else None,
                     delta=(float(np.mean(sb) - np.mean(sa)) if sa and sb else None),
                     perm_p=None, fdr_q=None)
            if na < MIN_SEEDS_FOR_PAIRWISE or nb < MIN_SEEDS_FOR_PAIRWISE:
                pairwise_rows.append(r)
                continue
            r["perm_p"] = perm_p(sa, sb)
            raw.append(r)
        for r, q in zip(raw, bh_fdr([r["perm_p"] for r in raw])):
            r["fdr_q"] = q
            pairwise_rows.append(r)

# ---- pairwise results table (machine-readable TSV + human-readable Markdown) ----
# minimum attainable two-sided p for n vs n via exact permutation = 2 / C(2n, n)
_min_p = {n: 2.0 / len(list(itertools.combinations(range(2 * n), n))) for n in (2, 3, 4, 5)}
_fam = len(list(itertools.combinations(PAIRS, 2)))
